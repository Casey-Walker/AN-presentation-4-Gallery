import json
import os
import shutil
import sys
from pathlib import Path

from chart_export import (
    KEY_FORWARD_SCRIPT,
    download_text,
    rewrite_pyldavis_urls,
    write_geo_assets_js,
    write_vendor_plotly_js,
)
from chart_meta import CHART_META, validate
from notebook_exec import build_working_copy, collect_stream_warnings, execute_notebook

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
SRC_IPYNB = PROJECT_ROOT / "Presentation 4 - Metro Analytics Notebook.ipynb"
BUILD_DIR = PROJECT_ROOT / ".superpowers" / "build"
BACKUP_DIR = BUILD_DIR / "site_backup"
WORKING_COPY = BUILD_DIR / "working_copy.ipynb"
DOCS_DIR = PROJECT_ROOT / "interactive-dashboard"
VENDOR_DIR = DOCS_DIR / "vendor"
VENDOR_JS = VENDOR_DIR / "plotly.min.js"
GEO_ASSETS_JS = VENDOR_DIR / "geo-assets.js"
RAW_MANIFEST = DOCS_DIR / "_manifest_raw.jsonl"
CHARTS_JS = DOCS_DIR / "charts.js"
PYLDAVIS_SRC = PROJECT_ROOT / "pyldavis_topics.html"
PYLDAVIS_DST = DOCS_DIR / "charts" / "pyldavis.html"
PYLDAVIS_ENTRY = {
    "id": "29_lda",
    "title": "LDA Topic Model (pyLDAvis)",
    "file": "charts/pyldavis.html",
    "thumbnail": None,
    "interactive": True,
}

# Vendored so the pyLDAvis panel also works with no internet access, same as
# every Plotly chart. URL -> local file under interactive-dashboard/vendor/.
PYLDAVIS_VENDOR_FILES = {
    "https://cdn.jsdelivr.net/gh/bmabey/pyLDAvis@3.4.0/pyLDAvis/js/ldavis.v1.0.0.css": "ldavis.v1.0.0.css",
    "https://d3js.org/d3.v5.js": "d3.v5.js",
    "https://d3js.org/d3.v5": "d3.v5.js",
    "https://cdn.jsdelivr.net/gh/bmabey/pyLDAvis@3.4.0/pyLDAvis/js/ldavis.v3.0.0.js": "ldavis.v3.0.0.js",
}

# Regenerated by this script; everything else in interactive-dashboard/
# (index.html, app.js, styles.css) is hand-authored and left alone.
GENERATED_SITE_PATHS = ["charts", "images", "thumbs", "vendor", "charts.js"]


def _backup_site() -> None:
    shutil.rmtree(BACKUP_DIR, ignore_errors=True)
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    for name in GENERATED_SITE_PATHS:
        src = DOCS_DIR / name
        if not src.exists():
            continue
        dst = BACKUP_DIR / name
        if src.is_dir():
            shutil.copytree(src, dst)
        else:
            shutil.copy2(src, dst)


def _restore_site_from_backup() -> None:
    for name in GENERATED_SITE_PATHS:
        dst = DOCS_DIR / name
        if dst.is_dir():
            shutil.rmtree(dst, ignore_errors=True)
        elif dst.exists():
            dst.unlink()
        src = BACKUP_DIR / name
        if src.exists():
            if src.is_dir():
                shutil.copytree(src, dst)
            else:
                shutil.copy2(src, dst)


def _clean_build_outputs() -> None:
    for d in ("charts", "images", "thumbs"):
        shutil.rmtree(DOCS_DIR / d, ignore_errors=True)
    RAW_MANIFEST.unlink(missing_ok=True)
    PYLDAVIS_SRC.unlink(missing_ok=True)  # stale copy from an earlier manual notebook run


def _vendor_pyldavis_assets() -> dict:
    url_to_local = {}
    for url, filename in PYLDAVIS_VENDOR_FILES.items():
        local_path = VENDOR_DIR / filename
        if not local_path.exists():
            download_text(url, str(local_path))
        url_to_local[url] = f"../vendor/{filename}"
    return url_to_local


class _ValidationFailed(Exception):
    pass


def _build() -> int:
    if not VENDOR_JS.exists():
        write_vendor_plotly_js(str(VENDOR_JS))
    if not GEO_ASSETS_JS.exists():
        write_geo_assets_js(str(GEO_ASSETS_JS))

    build_working_copy(str(SRC_IPYNB), str(WORKING_COPY))
    execute_notebook(str(WORKING_COPY), cwd=str(PROJECT_ROOT))

    for line in collect_stream_warnings(str(WORKING_COPY)):
        print(line)

    raw_entries = []
    if RAW_MANIFEST.exists():
        with open(RAW_MANIFEST, encoding="utf-8") as f:
            raw_entries = [json.loads(line) for line in f if line.strip()]

    if PYLDAVIS_SRC.exists():
        PYLDAVIS_DST.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(str(PYLDAVIS_SRC), str(PYLDAVIS_DST))
        url_to_local = _vendor_pyldavis_assets()
        with open(PYLDAVIS_DST, encoding="utf-8") as f:
            html = f.read()
        html = rewrite_pyldavis_urls(html, url_to_local)
        html = html.replace("</body>", f"<script>{KEY_FORWARD_SCRIPT}</script></body>")
        with open(PYLDAVIS_DST, "w", encoding="utf-8") as f:
            f.write(html)
        raw_entries.append(PYLDAVIS_ENTRY)

    found_ids = [e["id"] for e in raw_entries]
    missing, extra = validate(found_ids)
    print(f"{len(missing)} missing, {len(extra)} extra")
    if missing:
        print("missing (no CHART_META entry):", missing)
    if extra:
        print("extra (in CHART_META but not produced):", extra)
    if missing or extra:
        raise _ValidationFailed(f"{len(missing)} missing, {len(extra)} extra")

    merged = []
    for entry in raw_entries:
        meta = CHART_META.get(entry["id"], {"section": "Uncategorized", "subsection": None, "caption": ""})
        merged.append({**entry, **meta})

    with open(CHARTS_JS, "w", encoding="utf-8") as f:
        f.write("window.CHARTS = ")
        json.dump(merged, f, indent=2)
        f.write(";\n")

    n_interactive = sum(1 for e in merged if e["interactive"])
    n_static = sum(1 for e in merged if not e["interactive"])
    no_thumb = [e["id"] for e in merged if e.get("thumbnail") is None]
    print(f"{n_interactive} interactive, {n_static} static charts exported")
    if no_thumb:
        print("no thumbnail:", no_thumb)

    return 0


def main(argv: list[str] | None = None) -> int:
    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    _backup_site()
    _clean_build_outputs()

    try:
        return _build()
    except _ValidationFailed as exc:
        print(f"validation failed ({exc}) -- restoring the previous gallery, nothing was changed")
        _restore_site_from_backup()
        return 1
    except Exception as exc:
        print(f"build failed ({exc}) -- restoring the previous gallery, nothing was changed")
        _restore_site_from_backup()
        raise


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
